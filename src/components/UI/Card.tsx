import { cn } from "@/utilities/stylingUtil";
import * as React from "react";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "surface-glass rounded-lg text-card-foreground transition-shadow duration-300",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

const CardHeader = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn("flex flex-col space-y-1.5 p-6", className)}
    {...props}
  />
));
CardHeader.displayName = "CardHeader";

const CardTitle = React.forwardRef<
  HTMLParagraphElement,
  React.HTMLAttributes<HTMLHeadingElement>
>(({ className, ...props }, ref) => (
  <h3
    ref={ref}
    className={cn(
      // Titles can be a bare 64-byte address or a long token name with no
      // break opportunity; anywhere-wrapping keeps them inside the card.
      "text-2xl font-semibold leading-tight tracking-tight [overflow-wrap:anywhere]",
      className,
    )}
    {...props}
  />
));
CardTitle.displayName = "CardTitle";

